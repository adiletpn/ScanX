# ─────────────────────────────────────────────────────────────
# Усталость
# ─────────────────────────────────────────────────────────────

#: Порог моргания задаём ОТНОСИТЕЛЬНО медианного EAR этого человека:
#: разрез глаз у всех разный, абсолютный порог работает плохо.
#: Значение подобрано по реальным записям: при 0.75 детектор пропускал
#: почти все моргания. Причина в том, что MediaPipe не отдаёт полностью
#: сомкнутое веко — на быстром моргании EAR проседает лишь на 10–20%
#: от медианы, а не до нуля, как на статичных фотографиях из статей.
