# ─────────────────────────────────────────────────────────────
# MediaPipe Face Mesh
# ─────────────────────────────────────────────────────────────

FACE_MESH_MAX_FACES: Final[int] = 1
FACE_MESH_MIN_DETECTION_CONFIDENCE: Final[float] = 0.5
FACE_MESH_MIN_TRACKING_CONFIDENCE: Final[float] = 0.5

#: refine_landmarks=True добавляет точные контуры глаз — нужны для EAR.
FACE_MESH_REFINE_LANDMARKS: Final[bool] = True

#: Face Mesh запускаем не на каждом кадре: детектор — самая дорогая часть
#: конвейера, а лицо между соседними кадрами почти не сдвигается. Средние RGB
#: при этом считаем на КАЖДОМ кадре, иначе потеряем пульсовой сигнал.
#: 1 — обрабатывать все кадры, 2 — каждый второй.
FACE_MESH_EVERY_N: Final[int] = 2

#: Сколько кадров из начала записи брать для пробы ориентации.
#: Один кадр может оказаться смазанным, пяти достаточно для уверенного ответа.
ORIENTATION_PROBE_FRAMES: Final[int] = 5

#: Порог уверенности детектора при пробе ориентации.
#: На штатных 0.5 детектор находит лицо и вверх ногами, и обе ориентации
#: выглядят одинаково хорошими. Замер на реальной записи: при 0.5 счёт 5:5,
#: начиная с 0.7 — 0:5, то есть перевёрнутый вариант отсекается полностью.
#: Берём 0.8 с запасом.
ORIENTATION_PROBE_CONFIDENCE: Final[float] = 0.8

#: Коэффициент экспоненциального сглаживания ландмарок (EMA).
#: 0.0 — не сглаживаем вовсе, 0.9 — сильное сглаживание с задержкой.
#: 0.6 убирает дрожание детектора, не «замыливая» моргания.
LANDMARK_EMA_ALPHA: Final[float] = 0.6

# ── ROI: области, по которым считаем кровоток ────────────────
# Индексы точек Face Mesh (468 точек, +10 при refine_landmarks).
# ROI строим как выпуклую оболочку этих точек — так результат не разваливается
# от неточности в одном-двух индексах и легко правится по отладочному кадру.

#: Лоб — самая надёжная зона для rPPG: тонкая кожа, хорошее кровоснабжение,
#: не двигается при речи и мимике.
ROI_FOREHEAD: Final[list[int]] = [
    67, 109, 10, 338, 297,   # верхняя дуга по линии роста волос
    334, 296, 336, 9, 107, 66, 105,  # нижняя граница над бровями
]

#: Левая щека (левая на изображении).
ROI_LEFT_CHEEK: Final[list[int]] = [116, 123, 147, 187, 205, 36, 142, 126]

#: Правая щека (зеркально).
ROI_RIGHT_CHEEK: Final[list[int]] = [345, 352, 376, 411, 425, 266, 371, 355]

#: Отступ внутрь от границы ROI, в долях высоты лица. Нужен, чтобы в маску
#: не попали волосы и края лица с резким перепадом яркости.
#: Значение маленькое намеренно: щека имеет высоту около 18% от лица,
#: и отступ в 6% срезал бы её с обеих сторон почти полностью — на реальной
#: записи от щеки оставался треугольник в несколько пикселей, а от лба
#: полоска по линии волос. Отступ должен быть заметно меньше самой узкой
#: из областей.
ROI_SHRINK_RATIO: Final[float] = 0.012

# ── Ландмарки для модуля усталости ───────────────────────────
# Классическая 6-точечная схема EAR (Soukupová & Čech, 2016),
# перенесённая на индексы MediaPipe.
# Порядок: [внешний угол, верх-1, верх-2, внутренний угол, низ-2, низ-1]

EYE_LEFT: Final[list[int]] = [33, 160, 158, 133, 153, 144]
EYE_RIGHT: Final[list[int]] = [362, 385, 387, 263, 373, 380]

#: Рот для MAR (зевание): углы + верхняя и нижняя губа изнутри.
MOUTH_CORNERS: Final[tuple[int, int]] = (61, 291)
MOUTH_VERTICAL: Final[tuple[int, int]] = (13, 14)

#: Опорные точки для оценки размера лица (нормировка движения головы).
FACE_ANCHOR_TOP: Final[int] = 10     # макушка лба
FACE_ANCHOR_BOTTOM: Final[int] = 152  # подбородок
