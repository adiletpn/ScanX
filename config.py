# ─────────────────────────────────────────────────────────────
# rPPG: оценка пульса
# ─────────────────────────────────────────────────────────────

#: Частота, на которую интерполируем RGB-ряды. Видео с телефона имеет
#: переменный FPS, поэтому работаем не с номерами кадров, а с реальным
#: временем, приведённым к равномерной сетке.
RESAMPLE_FPS: Final[float] = 30.0

#: Алгоритм извлечения пульсового сигнала: "pos" (Wang et al., 2017)
#: или "green" — только зелёный канал (запасной, менее устойчив к движению).
RPPG_METHOD: Final[str] = "pos"

#: Полоса пропускания для пульса: 0.75–3.0 Гц = 45–180 уд/мин.
#: Шире не берём — попадёт дыхание снизу и шум сверху.
HR_BAND_HZ: Final[tuple[float, float]] = (0.75, 3.0)
HR_MIN_BPM: Final[float] = 45.0
HR_MAX_BPM: Final[float] = 180.0

#: Порядок фильтра Баттерворта. 4-й — компромисс между крутизной среза
#: и устойчивостью (реализуем через sos, иначе на высоких порядках плывёт).
FILTER_ORDER: Final[int] = 4

#: Скользящее окно оценки пульса: 10 с при шаге 1 с.
#: Итоговое значение — медиана по окнам, разброс — межквартильный размах.
HR_WINDOW_SEC: Final[float] = 10.0
HR_STEP_SEC: Final[float] = 1.0

#: Zero-padding перед БПФ: во сколько раз удлиняем сигнал нулями.
#: Даёт более гладкий спектр и точное положение пика после
#: параболической интерполяции.
FFT_PAD_FACTOR: Final[int] = 8

