def format_scan_context(
    hr: HeartRateResult | None,
    fatigue: FatigueResult | None,
    quality: QualityReport | None,
) -> str:
    """Собирает результаты скана в текст для контекста модели.

    При плохом качестве записи число пульса в контекст НЕ попадает:
    иначе модель начнёт уверенно рассуждать о цифре, полученной из шума,
    и эта уверенность передастся пользователю.
    """
    if hr is None and fatigue is None:
        return ""

    lines: list[str] = ["Данные скана этого пациента:"]

    if quality is not None:
        lines.append(f"- Качество записи: {quality.level.label.lower()}")

    trustworthy = quality is None or quality.level.is_trustworthy

    if hr is not None:
        if trustworthy:
            lines.append(
                f"- Пульс: около {hr.bpm:.0f} уд/мин "
                f"(разброс ±{hr.bpm_spread:.0f}, норма покоя "
                f"{config.HR_RESTING_NORMAL[0]:.0f}–{config.HR_RESTING_NORMAL[1]:.0f})"
            )
        else:
            lines.append(
                "- Пульс: измерить не удалось, запись плохого качества. "
                "Не называй никаких чисел пульса."
            )

    if fatigue is not None and fatigue.reliable:
        lines.append(
            f"- Индекс усталости: {fatigue.index:.0f} из 100 "
            f"({fatigue.level.label.lower()})"
        )
        lines.append(f"- Морганий в минуту: {fatigue.blink_rate_per_min:.0f}")
        if fatigue.yawn_count > 0:
            lines.append(f"- Зевков за запись: {fatigue.yawn_count}")

    lines.append(
        "Замеры сделаны камерой телефона — это ориентир, а не лабораторное "
        "измерение. Учитывай их, но не строй выводы на одних цифрах."
    )
    return "\n".join(lines)


def build_vision_prompt() -> str:
    """Промпт для разбора фото медицинского документа."""
    return (
        "На фото — медицинский документ. Выпиши показатели таблицей: "
        "название, значение, единицы, референсный диапазон с бланка. "
        "Если цифра неразборчива — напиши «не видно», не угадывай. "
        "После таблицы разбери результаты: что означает каждый показатель, "
        "что выходит за референс, о чём это обычно говорит и что делать дальше."
    )
