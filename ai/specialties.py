#: Быстрый доступ по ключу.
BY_KEY: dict[str, Specialty] = {s.key: s for s in SPECIALTIES}

#: Терапевт — вход по умолчанию, как и в обычной поликлинике.
DEFAULT_KEY = "therapist"


def get(key: str | None) -> Specialty:
    """Возвращает специальность по ключу, по умолчанию — терапевта."""
    return BY_KEY.get(key or DEFAULT_KEY, BY_KEY[DEFAULT_KEY])


def match_by_name(name: str) -> Specialty | None:
    """Находит специальность по названию из ответа модели.

    Модель пишет специальность свободным текстом — «невролог»,
    «врач-невролог», «неврологу». Сравниваем по корню названия,
    чтобы заключение можно было передать нужному специалисту одной кнопкой.
    """
    lowered = name.strip().lower()
    if not lowered:
        return None
    for specialty in SPECIALTIES:
        root = specialty.name.lower()[:5]
        if root in lowered:
            return specialty
    return None
