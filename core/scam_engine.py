"""Движок распознавания телефонного мошенничества.

Построен по той же схеме, что ``triage_engine``: жёсткие правила, явные веса,
объяснимое решение. Причина та же и даже острее — здесь система кричит
пожилому человеку «вам звонит мошенник», и ошибка стоит доверия. Второй раз
её слушать не станут.

**Ключевая идея: мы ловим не слова, а схему.**

Мошенник может как угодно менять формулировки, но он обязан добиться от
жертвы конкретных действий: назвать код из СМС, перевести деньги, установить
программу удалённого доступа. Эти действия и есть скелет схемы, и обойти их
нельзя — без них мошенничество не состоится.

Отсюда же устойчивость к плохому распознаванию речи. Расшифровка будет
кривой, особенно на казахском, но опорные корни — «банк», «код», «аудар»,
«қауіпсіз» — мошеннику придётся произнести.

Отдельная забота — **не сработать на настоящем банке**. Поэтому есть
защитные признаки: фразы, которые снижают оценку риска, и порог, ниже
которого система молчит. Промолчать на настоящем звонке дешевле, чем
напугать бабушку из-за слова «банк».
"""

from __future__ import annotations

import logging
import re
import unicodedata
from dataclasses import dataclass, field
from enum import Enum

log = logging.getLogger(__name__)


class RiskLevel(str, Enum):
    """Уровень тревоги. Именно уровень, а не «да/нет»."""

    CALM = "calm"
    WATCH = "watch"
    ALERT = "alert"
    DANGER = "danger"

    @property
    def weight(self) -> int:
        return {"calm": 0, "watch": 1, "alert": 2, "danger": 3}[self.value]

    @property
    def label(self) -> str:
        return {
            "calm": "Обычный разговор",
            "watch": "Есть подозрительное",
            "alert": "Похоже на мошенников",
            "danger": "Это мошенники",
        }[self.value]

    @property
    def emoji(self) -> str:
        return {"calm": "🟢", "watch": "🟡", "alert": "🟠", "danger": "🔴"}[self.value]

    @property
    def should_warn(self) -> bool:
        """Говорить ли вслух родителю."""
        return self.weight >= RiskLevel.ALERT.weight

    @property
    def should_notify(self) -> bool:
        """Отправлять ли уведомление детям."""
        return self.weight >= RiskLevel.ALERT.weight


@dataclass(frozen=True)
class ScamPattern:
    """Одна схема мошенничества."""

    code: str
    name: str

    stems: tuple[tuple[str, ...], ...]
    """Варианты распознавания: набор корней, которые должны встретиться вместе.
    Русский и казахский лежат в одном списке — мошенники в Казахстане часто
    мешают языки прямо внутри разговора, и разделять их было бы вредно."""

    weight: float
    """Вклад в оценку риска."""

    explanation: str
    """Что показать человеку: почему это подозрительно."""

    decisive: bool = False
    """Признак, которого достаточно самого по себе.
    Такие вещи настоящий банк не делает НИКОГДА."""

    strong: bool = False
    """Схема, одной которой хватает для тревоги.

    Нужна, потому что порог по сумме баллов пропускал одиночные, но
    самодостаточные требования: «сколько денег у вас есть» набирало
    6 баллов при пороге 8 — система схему распознавала и молчала.
    Складывать признаки имеет смысл, когда каждый сам по себе слаб;
    здесь это не так."""


@dataclass
class ScamDecision:
    """Решение движка — полностью объяснимое."""

    level: RiskLevel
    score: float
    matched: list[ScamPattern] = field(default_factory=list)
    safe_signals: list[str] = field(default_factory=list)
    reasons: list[str] = field(default_factory=list)
    transcript: str = ""

    @property
    def headline(self) -> str:
        """Короткая причина для крупной надписи на экране."""
        if not self.matched:
            return "Подозрительных признаков нет"
        return self.matched[0].name


