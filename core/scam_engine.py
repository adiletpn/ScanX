#: Границы уровней по итоговому баллу.
THRESHOLD_WATCH = 4.0
THRESHOLD_ALERT = 8.0
THRESHOLD_DANGER = 12.0

#: Чередования гласных в корне — та же проблема, что в triage_engine.
_STEM_ALIASES: dict[str, tuple[str, ...]] = {
    "бол": ("бол", "бал"),
    "звон": ("звон", "зван"),
    "спис": ("спис", "спиш"),
}


def _normalize(text: str) -> str:
    """Убирает регистр, ё→е и пунктуацию.

    Расшифровка речи приходит без знаков препинания и в нижнем регистре,
    но нормализуем всё равно: тексты приходят и из тестов, и из файлов.
    """
    lowered = unicodedata.normalize("NFKC", text).lower().replace("ё", "е")
    return re.sub(r"[^а-яa-zәғқңөұүһі0-9\s]", " ", lowered)


def _stem_present(stem: str, text: str) -> bool:
    for variant in _STEM_ALIASES.get(stem, (stem,)):
        if variant in text:
            return True
    return False


#: Насколько близко должны стоять корни одного варианта, в словах.
#: Реальные фразы схем укладываются в пять: «назовите код из смс» — четыре,
#: «переведите деньги на безопасный счёт» — пять.
#: Замеряно на настоящей расшифровке: при окне в восемь слов «служба
#: БЕЗОПАСНости банка… по вашему СЧЁТу» (шесть слов между корнями)
#: срабатывало как «переведите на безопасный счёт».
PROXIMITY_WINDOW = 5


def _variant_in_window(words: list[str], stems: tuple[str, ...]) -> bool:
    """Проверяет, что все корни варианта стоят рядом друг с другом.

    Это принципиально, а не косметика. Если искать корни по всему тексту,
    то в длинном разговоре они пересекутся сами собой: «служба БЕЗОПАСНости
    банка… по вашему СЧЁТу» срабатывало как «переведите на безопасный счёт»,
    хотя ни о каком переводе речи не было. Чем дольше идёт звонок,
    тем больше таких случайных совпадений.
    """
    normalized = [_normalize(stem).strip() for stem in stems]

    if len(normalized) == 1:
        return any(_stem_present(normalized[0], word) for word in words)

    for start in range(len(words)):
        window = words[start : start + PROXIMITY_WINDOW]
        if all(
            any(_stem_present(stem, word) for word in window)
            for stem in normalized
        ):
            return True
    return False


def _matches(text: str, variants: tuple[tuple[str, ...], ...]) -> bool:
    """Ищет хотя бы один вариант, чьи корни стоят рядом."""
    words = text.split()
    for variant in variants:
        if _variant_in_window(words, variant):
            return True
    return False


def evaluate(transcript: str) -> ScamDecision:
    """Оценивает расшифровку разговора.

    Args:
        transcript: текст, накопленный с начала звонка.

    Returns:
        ScamDecision с уровнем тревоги, баллом и списком сработавшего.
    """
    text = _normalize(transcript)

    matched: list[ScamPattern] = []
    reasons: list[str] = []
    score = 0.0

    # ── Решающие признаки ──
    for pattern in DECISIVE:
        if _matches(text, pattern.stems):
            matched.append(pattern)
            score += pattern.weight
            reasons.append(f"🚩 {pattern.name}: {pattern.explanation}")

    # ── Обычные схемы ──
    for pattern in PATTERNS:
        if _matches(text, pattern.stems):
            matched.append(pattern)
            score += pattern.weight
            reasons.append(f"• {pattern.name}: {pattern.explanation}")

    # Сочетание схем опаснее их суммы: настоящий разговор редко содержит
    # сразу три признака, а мошенническая схема — почти всегда.
    if len(matched) >= 3:
        score += 3.0
        reasons.append("• Несколько признаков подряд — так строится схема обмана")

    # ── Защитные признаки ──
    safe: list[str] = []
    for variants, description, relief in SAFE_SIGNALS:
        if _matches(text, variants):
            safe.append(description)
            score -= relief
            reasons.append(f"✓ Успокаивающий признак: {description}")

    score = max(score, 0.0)

    # ── Уровень ──
    # Сильная защита гасит решающий признак: собеседник, который сам
    # отговаривает называть код или предлагает перезвонить по номеру
    # с карты, мошенником не бывает. Промолчать здесь дешевле,
    # чем напугать человека на настоящем звонке из банка.
    has_decisive = any(p.decisive for p in matched) and not safe
    has_strong = any(getattr(p, "strong", False) for p in matched) and not safe

    if has_decisive:
        # Решающий признак поднимает тревогу независимо от балла:
        # просьба назвать код из СМС не нуждается в подтверждениях.
        level = RiskLevel.DANGER
    elif score >= THRESHOLD_DANGER:
        level = RiskLevel.DANGER
    elif score >= THRESHOLD_ALERT or has_strong:
        # Самодостаточная схема поднимает тревогу, не дожидаясь суммы.
        level = RiskLevel.ALERT
    elif score >= THRESHOLD_WATCH:
        level = RiskLevel.WATCH
    else:
        level = RiskLevel.CALM

    log.info(
        "Риск %s (балл %.1f), схем: %s",
        level.value, score, [p.code for p in matched] or "нет",
    )

    return ScamDecision(
        level=level,
        score=score,
        matched=matched,
        safe_signals=safe,
        reasons=reasons,
        transcript=transcript,
    )


def warning_text(decision: ScamDecision) -> str:
    """Текст, который произносится вслух родителю.

    Короткий и конкретный: в момент давления длинное объяснение
    не воспринимается. Главное — прервать разговор.
    """
    if not decision.level.should_warn:
        return ""

    top = decision.matched[0] if decision.matched else None
    if top is not None and top.decisive:
        return (
            f"Внимание. {top.name}. "
            "Это мошенники. Положите трубку и позвоните в банк сами."
        )
    return (
        "Внимание. Разговор похож на мошеннический. "
        "Положите трубку и перезвоните близким."
    )
