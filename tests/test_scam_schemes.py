"""Схемы, распространённые в Казахстане.

Добавлены после того, как стало ясно: первый набор правил закрывал
банковские схемы и «родственника в беде», но не трогал то, на что
ловят пожилых не реже — выигрыши, компенсации, пенсионные перерасчёты.

Вторая половина файла важнее первой. Каждая новая схема расширяет
область срабатывания, а значит повышает риск закричать на обычный
звонок из поликлиники или от курьера. Эти тесты держат границу.
"""

from __future__ import annotations

import pytest

from core.scam_engine import RiskLevel, evaluate


# ─────────────────────────────────────────────────────────────
# Схемы, на которые ловят пожилых
# ─────────────────────────────────────────────────────────────


@pytest.mark.parametrize(
    "text",
    [
        "поздравляем ваш номер выиграл автомобиль надо оплатить доставку приза",
        "вы выиграли в лотерее нашего банка",
        "ваш счастливый номер выбран среди тысячи участников",
    ],
)
def test_prize_scheme(text: str) -> None:
    """Выигрыш там, где человек не участвовал."""
    assert evaluate(text).level.should_warn, text


@pytest.mark.parametrize(
    "text",
    [
        "вам положена компенсация от государства за неиспользованные лекарства",
        "полагается выплата по программе поддержки пенсионеров",
        "оформляем возврат денежных средств за прошлые годы",
    ],
)
def test_compensation_scheme(text: str) -> None:
    """Обещанная компенсация — классика обмана пожилых."""
    assert evaluate(text).level.should_warn, text


@pytest.mark.parametrize(
    "text",
    [
        "звоним из пенсионного фонда по перерасчету пенсии подтвердите данные",
        "вам полагается доплата к пенсии надо срочно оформить",
        "из енпф беспокоят по вашим накоплениям назовите иин",
    ],
)
def test_pension_scheme(text: str) -> None:
    """Пенсионная тема бьёт точно по нашей аудитории.

    Пожилой человек ждёт новостей о пенсии, и это снимает настороженность.
    """
    decision = evaluate(text)
    assert decision.level is not RiskLevel.CALM, text


@pytest.mark.parametrize(
    "text",
    [
        "ваши данные скомпрометированы посторонние получили доступ к аккаунту",
        "произошла утечка данных надо срочно защитить счет",
    ],
)
def test_data_leak_scheme(text: str) -> None:
    assert evaluate(text).level is not RiskLevel.CALM, text


@pytest.mark.parametrize(
    "text",
    [
        "предлагаем инвестиционную платформу гарантированный доход двадцать процентов",
        "вложите средства и заработайте на криптовалюте",
    ],
)
def test_investment_scheme(text: str) -> None:
    assert evaluate(text).level is not RiskLevel.CALM, text


def test_fake_delivery_scheme() -> None:
    """Посылка, которую не заказывали, с просьбой оплатить сбор."""
    text = "вам посылка которую вы не заказывали оплатите таможенный сбор"
    assert evaluate(text).level is not RiskLevel.CALM


# ─────────────────────────────────────────────────────────────
# Граница: обычные звонки должны остаться тихими
# ─────────────────────────────────────────────────────────────


@pytest.mark.parametrize(
    "text",
    [
        "здравствуйте курьер привезет ваш заказ через час будьте дома",
        "напоминаем о записи к врачу завтра ничего оплачивать не надо",
        "ваш документ готов получите в отделении по паспорту",
        "здравствуйте это классный руководитель завтра родительское собрание",
        "передайте показания счетчика до конца месяца",
        "какая сумма вас интересует по вкладу приходите в отделение",
        "сәлеметсіз бе емханадан хабарласып тұрмыз дәрігерге жазылғансыз",
        "это банк информируем об изменении тарифа никаких действий не требуется",
        "ваша пенсия зачислена можете получить в отделении почты",
    ],
)
def test_ordinary_calls_stay_silent(text: str) -> None:
    """Расширение схем не должно превратить систему в крикунью.

    Каждая новая схема повышает риск ложной тревоги. Человек, напуганный
    зря, выключит приложение и не включит больше никогда — и тогда оно
    не сработает в тот единственный раз, когда действительно нужно.
    """
    decision = evaluate(text)
    assert not decision.level.should_warn, (
        f"ложная тревога ({decision.score:.1f}): {text}"
    )
