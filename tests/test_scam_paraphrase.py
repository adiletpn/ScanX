# ─────────────────────────────────────────────────────────────
# И по-прежнему молчим на обычном
# ─────────────────────────────────────────────────────────────


@pytest.mark.parametrize(
    "text",
    [
        "здравствуйте вы заказывали доставку курьер будет через час",
        "мам я задержусь на работе поужинайте без меня",
        "напоминаем о записи к стоматологу завтра в три часа",
        "ваша посылка прибыла в отделение получите по паспорту",
        "это банк перезвоните нам сами по номеру на обороте карты",
        "никому не сообщайте код из смс мы его никогда не спрашиваем",
        "сколько вам лет для оформления страховки",
        "какая сумма вас интересует по вкладу приходите в отделение",
    ],
)
def test_normal_speech_stays_silent(text: str) -> None:
    """Расширение правил не должно превратить систему в крикунью.

    Каждый новый корень — риск ложной тревоги. Этот тест держит границу.
    """
    decision = evaluate(text)
    assert decision.level is RiskLevel.CALM, (
        f"ложная тревога ({decision.score:.1f}): {text}"
    )
