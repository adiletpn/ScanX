# ─────────────────────────────────────────────────────────────
# Вопрос о деньгах
# ─────────────────────────────────────────────────────────────


@pytest.mark.parametrize(
    "text",
    [
        "какой суммой вы располагаете прямо сейчас наличными",
        "сколько денег у вас есть на карте",
        "какая сумма имеется в наличии",
        "сколько вы готовы внести сегодня",
    ],
)
def test_money_question_any_wording(text: str) -> None:
    """Вопрос о доступной сумме — сильнейший признак.

    Ни банк, ни полиция никогда не спрашивают, какими деньгами
    человек располагает.
    """
    assert _warns(text), f"пропущено: {text}"


