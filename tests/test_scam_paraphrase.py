"""Враждебный набор: те же требования, но другими словами.

Мошенник не обязан говорить так, как записано в правилах. Он скажет
«продиктуйте цифры из сообщения» вместо «назовите код из СМС»,
«тимвьюер» вместо «TeamViewer», «какой суммой располагаете» вместо
«сколько можете собрать».

Этот файл существует, потому что первая версия движка проваливала
четыре перефразировки из семи. Каждый тест здесь — дыра, которая
реально была найдена, а не выдумана для красоты.
"""

from __future__ import annotations

import pytest

from core.scam_engine import RiskLevel, evaluate


def _warns(text: str) -> bool:
    return evaluate(text).level.should_warn


# ─────────────────────────────────────────────────────────────
# Просьба назвать код — разными словами
# ─────────────────────────────────────────────────────────────


@pytest.mark.parametrize(
    "text",
    [
        "сейчас придет сообщение продиктуйте мне цифры оттуда",
        "вам придет смс назовите эти четыре цифры",
        "какие цифры пришли в сообщении скажите мне",
        "прочитайте мне код подтверждения который пришел",
        "продиктуйте пароль из сообщения быстро",
        "сообщите пожалуйста цифры из смс для отмены операции",
    ],
)
def test_code_request_any_wording(text: str) -> None:
    """Просьба назвать код ловится независимо от формулировки."""
    assert _warns(text), f"пропущено: {text}"


# ─────────────────────────────────────────────────────────────
# Программа удалённого доступа
# ─────────────────────────────────────────────────────────────


@pytest.mark.parametrize(
    "text",
    [
        "загрузите в плей маркете тимвьюер мы посмотрим что у вас",
        "скачайте энидеск это займет минуту",
        "установите программу для удаленной помощи",
        "надо поставить приложение чтобы мы подключились к вашему телефону",
        "зайдите в магазин приложений и найдите quick support",
    ],
)
def test_remote_access_any_wording(text: str) -> None:
    """Просьба установить программу доступа ловится в любом написании.

    Названия программ в речи звучат кириллицей: «тимвьюер», «энидеск».
    Латинского написания в расшифровке не будет никогда.
    """
    assert _warns(text), f"пропущено: {text}"


